"""Unicycle--open-loop input vs feedback policy, with small steering noise."""
import numpy as np
import matplotlib.pyplot as plt

# State s = (x, y, phi), action (input) a = (v, u).
delta = 0.1   # discretization step
steps = 100   # number of simulation steps
x_goal, y_goal = 4.0, 3.0

# Open-loop input design: a unicycle at (0,0) heading phi = 0, with constant
# inputs v, u throughout the trajectory, traces a circle of
# radius r = v/u. We pick r so that circle passes through the goal.
# u_plan = v/r is the constant turning rate that keeps the robot on that circle.
# travel_time is how long to drive before the arc reaches the goal -- after
# that we stop turning. Without noise this arc reaches the target.
radius = (x_goal**2 + y_goal**2) / (2*y_goal)
turn_angle = 2*np.arctan2(y_goal, x_goal)
v_plan = 1.0                      # open-loop forward velocity
u_plan = v_plan / radius          # open-loop angular velocity
travel_time = radius * turn_angle / v_plan

N_RUNS = 20       # number of stochastic trials
NOISE_STD = 0.015 # steering noise standard deviation (radians)
rng = np.random.default_rng(7)


def simulate(closed_loop, noise):
    x, y, phi = 0.0, 0.0, 0.0  # initial condition
    xs, ys = [x], [y]

    for k in range(steps):
        if closed_loop:
            # Feedback: use current position and heading to steer toward goal.
            distance = np.sqrt((x_goal - x)**2 + (y_goal - y)**2)  # distance to goal
            desired_phi = np.arctan2(y_goal-y, x_goal-x)           # heading that points toward goal
            error = (desired_phi-phi+np.pi) % (2*np.pi) - np.pi    # heading error, normalized to [-pi, pi]
            v = min(1.0, distance)                                  # reduce speed near goal to avoid overshoot
            u = 2.0 * error                                         # proportional angle control
        else:
            # Open-loop: planned input sequence computed in advance.
            remaining = max(0.0, travel_time-k*delta)
            v = v_plan * min(1.0, remaining/delta)
            u = u_plan if remaining > 0 else 0.0

        # Euler discretization with a small random steering disturbance.
        x_next = x + delta*v*np.cos(phi)
        y_next = y + delta*v*np.sin(phi)
        phi_next = phi + delta*u + noise[k]
        x, y, phi = x_next, y_next, phi_next
        xs.append(x)
        ys.append(y)

    return np.array(xs), np.array(ys)


# --- Single-run plot (one noise realization, same for both) ---
noise_single = rng.normal(0, NOISE_STD, steps)
x_open,   y_open   = simulate(False, noise_single)
x_closed, y_closed = simulate(True,  noise_single)

plt.figure(figsize=(7, 5))
plt.plot(x_open,   y_open,   label="Open-loop (planned arc)", linewidth=2)
plt.plot(x_closed, y_closed, label="Closed-loop (feedback)",  linewidth=2)
plt.scatter([0],      [0],      c="black", marker="s",  label="Start")
plt.scatter([x_goal], [y_goal], c="red",   marker="*", s=170, label="Goal")
plt.xlabel("x (m)")
plt.ylabel("y (m)")
plt.title("Same small steering disturbance for both robots")
plt.axis("equal")
plt.grid(True)
plt.legend()
plt.tight_layout()
plt.show()

print(f"Open-loop distance to goal:   {np.sqrt((x_open[-1]-x_goal)**2  + (y_open[-1]-y_goal)**2):.2f} m")
print(f"Closed-loop distance to goal: {np.sqrt((x_closed[-1]-x_goal)**2 + (y_closed[-1]-y_goal)**2):.2f} m")


# --- Multi-run plot (N_RUNS independent noise draws) ---
fig, axes = plt.subplots(1, 2, figsize=(13, 5), sharey=True)
titles = ["Open-loop (planned arc)", "Closed-loop (feedback)"]

for ax, closed_loop, title in zip(axes, [False, True], titles):
    for i in range(N_RUNS):
        noise = rng.normal(0, NOISE_STD, steps)   # fresh noise each run
        xs, ys = simulate(closed_loop, noise)
        color = "tomato" if not closed_loop else "steelblue"
        ax.plot(xs, ys, color=color, alpha=0.35, linewidth=1)

    ax.scatter([0],      [0],      c="black", marker="s",  s=60,  zorder=5, label="Start")
    ax.scatter([x_goal], [y_goal], c="red",   marker="*", s=200, zorder=5, label="Goal")
    ax.set_title(title, fontsize=13)
    ax.set_xlabel("x (m)")
    ax.axis("equal")
    ax.grid(True, alpha=0.4)
    ax.legend()

axes[0].set_ylabel("y (m)")
fig.suptitle(f"{N_RUNS} stochastic runs, noise std = {NOISE_STD} rad", fontsize=13)
plt.tight_layout()
plt.show()